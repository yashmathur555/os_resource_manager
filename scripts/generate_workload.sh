#!/usr/bin/env bash
# Generate a reproducible random process workload CSV.
# Usage: generate_workload.sh <num_processes> <seed> <output.csv>
set -euo pipefail

n="${1:-8}"; seed="${2:-42}"; out="${3:-data/workload_generated.csv}"

if ! [[ "$n" =~ ^[0-9]+$ ]] || (( n < 1 || n > 500 )); then
    echo "error: number of processes must be an integer 1..500" >&2; exit 1
fi
if ! [[ "$seed" =~ ^[0-9]+$ ]]; then
    echo "error: seed must be a non-negative integer" >&2; exit 1
fi

RANDOM=$seed
mkdir -p "$(dirname "$out")"
{
    echo "# Generated by generate_workload.sh n=$n seed=$seed"
    echo "pid,arrival,burst,priority"
    arrival=0
    for ((i = 1; i <= n; i++)); do
        arrival=$(( arrival + RANDOM % 4 ))
        burst=$(( RANDOM % 15 + 1 ))
        prio=$(( RANDOM % 5 + 1 ))
        echo "P${i},${arrival},${burst},${prio}"
    done
} > "$out"
echo "wrote $out"
